import type { AstroIntegration, InjectedRoute } from 'astro';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  discoverForgeGateReportDataFiles,
  forgeGateReportDataDiscovery,
  registerForgeGateReportData,
  safeReportDataRoot,
  type ForgeGateReportDataFilesystemDiscovery,
  type ForgeGateReportDataDiscovery,
  type ForgeGateReportDataRegistrationEntry,
  type ForgeGateReportDataRegistration,
} from './report-data';

export const FORGEGATE_STARLIGHT_INTEGRATION_NAME = '@forgegate/starlight';
export const FORGEGATE_STARLIGHT_MINIMUM_ASTRO_VERSION = '5.0.0';
export const FORGEGATE_STARLIGHT_MINIMUM_STARLIGHT_VERSION = '0.41.0';

export interface ForgeGateStarlightIntegrationOptions {
  /**
   * Repository-root-relative data directory generated by ForgeGate. Kept
   * configurable so a future full plugin can discover data without requiring
   * generated MDX import paths to change.
   */
  readonly reportDataRoot?: string;
  readonly filesystemDiscovery?: boolean;
  readonly routeBase?: string;
  readonly routeInjection?: boolean;
  readonly workspaceRoot?: string;
  readonly astroVersion?: string;
  readonly starlightVersion?: string;
}

export interface ForgeGateStarlightLifecycleStatus {
  readonly integrationName: typeof FORGEGATE_STARLIGHT_INTEGRATION_NAME;
  readonly reportDataRoot: string;
  readonly reportData: ForgeGateReportDataDiscovery;
  readonly filesystemDiscovery: boolean;
  readonly lifecycle: 'discovery-contract' | 'filesystem-discovery';
  readonly supports: readonly string[];
  readonly planned: readonly string[];
}

export interface ForgeGateStarlightInjectedRoute {
  readonly kind: ForgeGateReportDataRegistrationEntry['kind'];
  readonly label: string;
  readonly reportDataPath: string;
  readonly routePath: string;
  readonly pattern: string;
  readonly entrypoint: string;
}

export interface ForgeGateStarlightCompatibilityDiagnostic {
  readonly level: 'info' | 'warning';
  readonly code: string;
  readonly message: string;
}

export function forgeGateStarlightLifecycleStatus(
  options: ForgeGateStarlightIntegrationOptions = {},
): ForgeGateStarlightLifecycleStatus {
  const reportDataRoot = safeReportDataRoot(
    options.reportDataRoot ?? 'src/data/forgegate/components',
  );
  return {
    integrationName: FORGEGATE_STARLIGHT_INTEGRATION_NAME,
    reportDataRoot,
    reportData: forgeGateReportDataDiscovery(reportDataRoot),
    filesystemDiscovery: options.filesystemDiscovery ?? false,
    lifecycle: options.filesystemDiscovery
      ? 'filesystem-discovery'
      : 'discovery-contract',
    supports: [
      'stable Astro integration name',
      'configurable generated report-data root',
      'generated-data discovery conventions',
      'component and registry report-data classification',
      'filesystem-backed report-data scanning when enabled',
      'deterministic report route registration plan',
      'version compatibility diagnostics',
      'optional Astro route injection from discovered report data',
      'manual MDX imports of ForgeGate presentation components',
      'manifest-backed component and registry report JSON',
    ],
    planned: [
      'migration guidance for generated MDX pages',
    ],
  };
}

export function forgeGateStarlightCompatibilityDiagnostics(
  options: ForgeGateStarlightIntegrationOptions = {},
): readonly ForgeGateStarlightCompatibilityDiagnostic[] {
  const diagnostics: ForgeGateStarlightCompatibilityDiagnostic[] = [];
  try {
    safeReportDataRoot(options.reportDataRoot ?? 'src/data/forgegate/components');
  } catch (error) {
    diagnostics.push({
      level: 'warning',
      code: 'unsafe-report-data-root',
      message: String(error),
    });
  }
  diagnostics.push(
    ...minimumVersionDiagnostics({
      name: 'Astro',
      code: 'astro-version-unknown',
      tooOldCode: 'astro-version-unsupported',
      actual: options.astroVersion,
      minimum: FORGEGATE_STARLIGHT_MINIMUM_ASTRO_VERSION,
    }),
    ...minimumVersionDiagnostics({
      name: 'Starlight',
      code: 'starlight-version-unknown',
      tooOldCode: 'starlight-version-unsupported',
      actual: options.starlightVersion,
      minimum: FORGEGATE_STARLIGHT_MINIMUM_STARLIGHT_VERSION,
    }),
  );
  return diagnostics;
}

export function forgeGateStarlightIntegration(
  options: ForgeGateStarlightIntegrationOptions = {},
): AstroIntegration {
  const status = forgeGateStarlightLifecycleStatus(options);
  const diagnostics = forgeGateStarlightCompatibilityDiagnostics(options);

  return {
    name: FORGEGATE_STARLIGHT_INTEGRATION_NAME,
    hooks: {
      'astro:config:setup': async ({
        config,
        logger,
        createCodegenDir,
        injectRoute,
      }) => {
        logger.debug(
          `ForgeGate report data root configured as ${status.reportDataRoot}.`,
        );
        logger.debug(
          `ForgeGate Starlight lifecycle stage: ${status.lifecycle}.`,
        );
        logger.debug(
          `ForgeGate report data discovery glob: ${status.reportData.allReportsGlob}.`,
        );
        for (const diagnostic of diagnostics) {
          const line = `[${diagnostic.code}] ${diagnostic.message}`;
          if (diagnostic.level === 'warning') {
            logger.warn(line);
          } else {
            logger.debug(line);
          }
        }
        if (!status.filesystemDiscovery) {
          return;
        }
        const discovery = await forgeGateStarlightFilesystemDiscovery({
          ...options,
          workspaceRoot:
            options.workspaceRoot ??
            (config?.root ? fileURLToPath(config.root) : process.cwd()),
        });
        logger.debug(
          `ForgeGate discovered ${discovery.componentReports.length} component report data file(s).`,
        );
        logger.debug(
          discovery.registryPath
            ? `ForgeGate discovered registry report data at ${discovery.registryPath}.`
            : `ForgeGate did not discover registry report data under ${discovery.reportDataRoot}.`,
        );
        const registration = forgeGateStarlightReportDataRegistration(
          discovery,
          options,
        );
        logger.debug(
          `ForgeGate prepared ${registration.entries.length} report route registration entries under ${registration.routeBase}.`,
        );
        for (const entry of registration.entries) {
          logger.debug(
            `ForgeGate report registration ${entry.kind}: ${entry.reportDataPath} -> ${entry.href}`,
          );
        }
        if (options.routeInjection) {
          const injectedRoutes = await forgeGateStarlightInjectReportDataRoutes(
            registration,
            {
              workspaceRoot: discovery.workspaceRoot,
              createCodegenDir,
              injectRoute,
            },
          );
          logger.debug(
            `ForgeGate injected ${injectedRoutes.length} generated report route(s).`,
          );
          for (const route of injectedRoutes) {
            logger.debug(
              `ForgeGate injected ${route.kind} route ${route.pattern} from ${route.reportDataPath}.`,
            );
          }
        }
        for (const ignoredReport of discovery.ignoredReports) {
          logger.warn(
            `[ignored-report-data] ${ignoredReport.path}: ${ignoredReport.reason}`,
          );
        }
        for (const limitation of discovery.limitations) {
          logger.warn(`[report-data-discovery-limitation] ${limitation}`);
        }
      },
    },
  };
}

export function forgeGateStarlightFilesystemDiscovery(
  options: ForgeGateStarlightIntegrationOptions & { readonly workspaceRoot: string },
): Promise<ForgeGateReportDataFilesystemDiscovery> {
  return discoverForgeGateReportDataFiles({
    workspaceRoot: options.workspaceRoot,
    reportDataRoot: options.reportDataRoot,
  });
}

export function forgeGateStarlightReportDataRegistration(
  discovery: ForgeGateReportDataFilesystemDiscovery,
  options: ForgeGateStarlightIntegrationOptions = {},
): ForgeGateReportDataRegistration {
  return registerForgeGateReportData(discovery, {
    routeBase: options.routeBase,
  });
}

export async function forgeGateStarlightInjectReportDataRoutes(
  registration: ForgeGateReportDataRegistration,
  options: {
    readonly workspaceRoot: string;
    readonly createCodegenDir: () => URL;
    readonly injectRoute: (route: InjectedRoute) => void;
  },
): Promise<readonly ForgeGateStarlightInjectedRoute[]> {
  if (registration.entries.length === 0) {
    return [];
  }
  const codegenDir = options.createCodegenDir();
  const codegenPath = fileURLToPath(codegenDir);
  await mkdir(codegenPath, { recursive: true });

  const injectedRoutes: ForgeGateStarlightInjectedRoute[] = [];
  for (const entry of registration.entries) {
    const entrypoint = path.join(
      codegenPath,
      `${entry.routePath.replace(/[^\w.-]+/g, '__')}.astro`,
    );
    await writeFile(
      entrypoint,
      renderInjectedRoute(entry, {
        codegenPath,
        workspaceRoot: options.workspaceRoot,
      }),
      'utf8',
    );
    const route: InjectedRoute = {
      pattern: `/${entry.routePath}`,
      entrypoint,
      prerender: true,
    };
    options.injectRoute(route);
    injectedRoutes.push({
      kind: entry.kind,
      label: entry.label,
      reportDataPath: entry.reportDataPath,
      routePath: entry.routePath,
      pattern: route.pattern,
      entrypoint,
    });
  }
  return injectedRoutes;
}

function minimumVersionDiagnostics(input: {
  readonly name: 'Astro' | 'Starlight';
  readonly code: string;
  readonly tooOldCode: string;
  readonly actual?: string;
  readonly minimum: string;
}): readonly ForgeGateStarlightCompatibilityDiagnostic[] {
  if (!input.actual) {
    return [
      {
        level: 'info',
        code: input.code,
        message: `${input.name} version was not provided; ForgeGate cannot verify compatibility against ${input.minimum}.`,
      },
    ];
  }
  if (compareVersions(input.actual, input.minimum) < 0) {
    return [
      {
        level: 'warning',
        code: input.tooOldCode,
        message: `${input.name} ${input.actual} is below ForgeGate's tested minimum ${input.minimum}.`,
      },
    ];
  }
  return [];
}

function compareVersions(left: string, right: string): number {
  const leftParts = versionParts(left);
  const rightParts = versionParts(right);
  for (const index of [0, 1, 2] as const) {
    const delta = leftParts[index] - rightParts[index];
    if (delta !== 0) {
      return delta;
    }
  }
  return 0;
}

function renderInjectedRoute(
  entry: ForgeGateReportDataRegistrationEntry,
  options: {
    readonly codegenPath: string;
    readonly workspaceRoot: string;
  },
): string {
  const reportDataPath = path.resolve(
    options.workspaceRoot,
    ...entry.reportDataPath.split('/'),
  );
  const importPath = normalizeImportPath(
    path.relative(options.codegenPath, reportDataPath),
  );
  return entry.kind === 'registry'
    ? renderInjectedRegistryRoute(entry, importPath)
    : renderInjectedComponentRoute(entry, importPath);
}

function renderInjectedRegistryRoute(
  entry: ForgeGateReportDataRegistrationEntry,
  importPath: string,
): string {
  return `---
import StarlightPage from '@astrojs/starlight/components/StarlightPage.astro';
import { ComponentRegistry } from '@forgegate/starlight';
import forgegateRegistry from ${JSON.stringify(importPath)};

const title = ${JSON.stringify(entry.label)};
const description = 'Generated ForgeGate component registry overview.';
---

<StarlightPage frontmatter={{ title, description }}>
  <ComponentRegistry report={forgegateRegistry} />
</StarlightPage>
`;
}

function renderInjectedComponentRoute(
  entry: ForgeGateReportDataRegistrationEntry,
  importPath: string,
): string {
  return `---
import StarlightPage from '@astrojs/starlight/components/StarlightPage.astro';
import {
  AccessibilityRequirements,
  ApiTable,
  ComponentStatus,
  ConsumerValidation,
  EvidenceSummary,
  ReleaseHistory,
  StateMatrix,
  TokenTable,
} from '@forgegate/starlight';
import forgegateReport from ${JSON.stringify(importPath)};

const componentId = forgegateReport.componentId ?? ${JSON.stringify(entry.label)};
const tier = forgegateReport.tier ?? 'balanced';
const title = ${JSON.stringify(entry.label)};
const description = \`Manifest-backed ForgeGate report for \${componentId}.\`;
---

<StarlightPage frontmatter={{ title, description }}>
  <ComponentStatus component={componentId} tier={tier} report={forgegateReport} />

  <h2>Overview</h2>
  <p>
    This report summarizes the component contract, required design states, token mappings, accessibility procedure,
    and current assurance evidence from repository-owned ForgeGate report data.
  </p>

  <h2>States</h2>
  <StateMatrix component={componentId} tier={tier} report={forgegateReport} />

  <h2>Tokens</h2>
  <TokenTable component={componentId} tier={tier} report={forgegateReport} />

  <h2>API</h2>
  <ApiTable component={componentId} tier={tier} report={forgegateReport} />

  <h2>Accessibility</h2>
  <AccessibilityRequirements component={componentId} tier={tier} report={forgegateReport} />

  <h2>Assurance</h2>
  <EvidenceSummary component={componentId} tier={tier} report={forgegateReport} />
  <ConsumerValidation component={componentId} tier={tier} report={forgegateReport} />
  <ReleaseHistory component={componentId} tier={tier} report={forgegateReport} />
</StarlightPage>
`;
}

function normalizeImportPath(relativePath: string): string {
  const normalized = relativePath.replace(/\\/g, '/');
  return normalized.startsWith('.') ? normalized : `./${normalized}`;
}

function versionParts(version: string): readonly [number, number, number] {
  const match = version.match(/\d+(\.\d+)?(\.\d+)?/);
  const parts = (match?.[0] ?? '0.0.0')
    .split('.')
    .map((part) => Number.parseInt(part, 10));
  return [parts[0] ?? 0, parts[1] ?? 0, parts[2] ?? 0];
}
